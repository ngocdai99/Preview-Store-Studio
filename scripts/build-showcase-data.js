#!/usr/bin/env node
/**
 * Store Preview Studio · Showcase Data Generator
 *
 * Reads the real curated presets in /presets/*.json (the same files the
 * studio imports) and emits a slim, browser-ready bundle at
 * docs/showcase-data.js for the Interactive Mini-Studio on docs/marketing.html.
 *
 * Using a <script src> bundle (instead of fetch) keeps the landing page working
 * when opened via file:// as well as when hosted.
 *
 * Usage: node scripts/build-showcase-data.js   (or: npm run showcase)
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PRESETS_DIR = path.join(ROOT, 'presets');
const OUT_FILE = path.join(ROOT, 'docs', 'showcase-data.js');

// Display order + short labels for the showcase pills (include Store Preview Studio)
const ORDER = [
  { file: 'store-preview-studio-template.json', key: 'studio', tag: 'Studio' },
  { file: 'saas-app-template.json', key: 'taskflow', tag: 'SaaS' },
  { file: 'fitness-tracker-template.json', key: 'pulsefit', tag: 'Fitness' },
  { file: 'zenmind-meditation-template.json', key: 'zenmind', tag: 'Health' },
  { file: 'cyberstrike-rpg-game-template.json', key: 'cyberstrike', tag: 'Game' },
  { file: 'education-language-template.json', key: 'edulearn', tag: 'Edu' },
];

function slim(entry) {
  const raw = JSON.parse(fs.readFileSync(path.join(PRESETS_DIR, entry.file), 'utf8'));
  const f = raw.form || {};
  const s = raw.stats || {};
  return {
    key: entry.key,
    tag: entry.tag,
    label: (f.name || '').split(/[:—-]/)[0].trim(),
    name: f.name || '',
    sub: f.sub || '',
    short: f.short || '',
    promo: f.promo || '',
    dev: f.dev || '',
    catApple: f.catApple || f.cat || '',
    catGoogle: f.catGoogle || f.cat || '',
    email: f.email || 'support@flowcraft.studio',
    phone: f.phone || '+1 800-555-0199',
    addr: f.addr || 'Vietnam',
    desc: (f.desc || '').slice(0, 420),
    rating: s.rating || '4.9',
    count: s.count || '1K',
    rank: s.rank || '1',
    dl: s.dl || '10K+',
    age: s.age || '4+',
    iap: s.iap === 'iap',
    icon: raw.icon || '',
    feature: raw.featureGraphic || '',
    shots: Array.isArray(raw.shots) ? raw.shots.slice(0, 4) : [],
    reviews: Array.isArray(raw.reviews) ? raw.reviews : [],
  };
}

const data = ORDER.filter(e => fs.existsSync(path.join(PRESETS_DIR, e.file))).map(slim);
const banner = '/* AUTO-GENERATED by scripts/build-showcase-data.js from /presets/*.json — do not edit by hand. */\n';
fs.writeFileSync(OUT_FILE, banner + 'window.SPS_SHOWCASE_PRESETS = ' + JSON.stringify(data) + ';\n');

const kb = (fs.statSync(OUT_FILE).size / 1024).toFixed(1);
console.log(`✓ Showcase data: ${data.length} presets → ${path.relative(ROOT, OUT_FILE)} (${kb} KB)`);
